// Schema registry: schema/types.json is the one source; generators (adapters in ./generators) emit each format.
//   const S = require("./lib/schema"); S.load(); S.generators.ids(); S.generate("zod")  -> { file, text }
// Type strings: string | int | float | bool | datetime | json | <Enum> | <Type>, with suffix [] (list) and/or ? (optional).
const fs = require("fs"), path = require("path");
const { createRegistry } = require("../registry");

const ROOT = path.join(__dirname, "..", "..");
const SOURCE = path.join(ROOT, "schema", "types.json");
const OUT = path.join(ROOT, "schema", "gen");
const SCALARS = ["string", "int", "float", "bool", "datetime", "json"];

function parseType(t) {
  let s = String(t).trim(), optional = false, list = false;
  if (s.endsWith("?")) { optional = true; s = s.slice(0, -1); }
  if (s.endsWith("[]")) { list = true; s = s.slice(0, -2); }
  return { base: s, list, optional, scalar: SCALARS.includes(s) };
}

// Normalised model the generators read: { pkg, version, ld, enums:[{name,about,values}], types:[{name,about,ld,fields:[{name,about,ld,pattern,...parseType}]}], services }
function load(file = SOURCE) {
  const src = JSON.parse(fs.readFileSync(file, "utf8"));
  const enums = Object.entries(src.enums || {}).map(([name, e]) => ({ name, about: e.about || "", values: e.values }));
  const types = Object.entries(src.types).map(([name, t]) => ({
    name, about: t.about || "", ld: t.ld || null,
    fields: Object.entries(t.fields).map(([fname, f]) => ({ name: fname, about: f.about || "", ld: f.ld || null, pattern: f.pattern || null, ...parseType(f.type) })),
  }));
  const known = new Set([...SCALARS, ...enums.map((e) => e.name), ...types.map((t) => t.name)]);
  for (const t of types) for (const f of t.fields) if (!known.has(f.base)) throw new Error(`schema/types.json: ${t.name}.${f.name} has unknown type "${f.base}"`);
  for (const [sname, s] of Object.entries(src.services || {})) for (const [m, d] of Object.entries(s.methods)) for (const io of [d.input, d.output]) if (!types.some((t) => t.name === io)) throw new Error(`service ${sname}.${m}: unknown type ${io}`);
  return { pkg: src.package, version: src.version, about: src.about, ld: src.ld || {}, enums, types, services: src.services || {}, isEnum: (n) => enums.some((e) => e.name === n) };
}

// Order types so each is defined after the types it uses (needed by zod and pydantic without forward refs).
function ordered(model) {
  const byName = Object.fromEntries(model.types.map((t) => [t.name, t])), done = new Set(), out = [];
  const visit = (t) => { if (done.has(t.name)) return; done.add(t.name); for (const f of t.fields) if (byName[f.base]) visit(byName[f.base]); out.push(t); };
  model.types.forEach(visit);
  return out;
}

const generators = createRegistry("schema generator", { required: ["id", "file", "generate"] });
for (const f of fs.readdirSync(path.join(__dirname, "generators")).filter((f) => f.endsWith(".js")).sort()) generators.register(require(path.join(__dirname, "generators", f)));

const HEADER = (c) => `${c} Generated by scripts/schema.js from schema/types.json. Do not edit; change types.json and run npm run schema.`;
function generate(id, model = load()) { const g = generators.get(id); return { id, file: path.join(OUT, g.file), text: g.generate(model, { ordered: ordered(model), header: HEADER }) }; }
function generateAll(model = load()) { return generators.ids().map((id) => generate(id, model)); }

module.exports = { load, parseType, ordered, generators, generate, generateAll, SOURCE, OUT };
