#!/usr/bin/env node
// Precompute every Lab example's default run (baseline, variant, verdict). The runs are deterministic, so they are
// computed once here instead of on a cold serverless start (about 6 s for all examples, close to Vercel Hobby's 10 s
// limit). Runs with a reader's own parameters are still computed live (each one takes at most about 1.6 s).
//   npm run lab:results            write modules/lab/results.json
//   node scripts/lab-results.js --check   exit 1 if the file is out of date (preflight runs this; it only hashes)
const fs = require("node:fs"), path = require("node:path"), crypto = require("node:crypto");
const dir = path.join(__dirname, "..", "modules", "lab"), out = path.join(dir, "results.json");
// Everything a default run depends on: the examples and every runner's code.
const SOURCES = ["examples.json", "lab.js", "runners.js", "gym.js", "intent.js", "interp.js", "papers.js"];
const hash = () => crypto.createHash("sha256").update(SOURCES.map((f) => fs.readFileSync(path.join(dir, f), "utf8")).join("\0")).digest("hex").slice(0, 16);

if (process.argv.includes("--check")) {
  const have = fs.existsSync(out) ? JSON.parse(fs.readFileSync(out, "utf8")).hash : null, want = hash();
  if (have !== want) { console.log(`lab results: out of date (${have || "missing"} vs ${want}); run npm run lab:results`); process.exit(1); }
  console.log(`lab results: current (${want})`); process.exit(0);
}
const L = require("../modules/lab/lab"), t0 = Date.now(), results = {};
for (const e of L.EX.examples) results[e.id] = L.runExample(e.id);
fs.writeFileSync(out, JSON.stringify({ about: "Generated by scripts/lab-results.js from the files listed in it; do not edit. Preflight checks it is current.", hash: hash(), results }) + "\n");
console.log(`lab results: ${Object.keys(results).length} examples in ${Date.now() - t0} ms -> modules/lab/results.json (${Math.round(fs.statSync(out).size / 1024)} KB)`);
