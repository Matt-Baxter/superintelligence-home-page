#!/usr/bin/env node
// Element catalog at the terminal (REQ-072..REQ-075, proposed). Same catalog as /m/elements.
//   npm run elements -- report                 counts, completeness, alias conflicts, the DAG, overlay mismatches
//   npm run elements -- get <id|alias>         one descriptor as JSON
//   npm run elements -- export [dir]           elements.jsonld, shapes.ttl, elements.nq and catalog.md (default out/elements)
//   npm run elements -- check-vibe <checkout>  check a vibe-coding checkout's prompts.md files against their shapes and keys
const fs = require("node:fs"), path = require("node:path");
process.env.SITE_PROFILE = process.env.SITE_PROFILE || "extended";
const E = require("../packages/si-elements"), V = require("../modules/elements/vibe");
const [cmd = "report", arg] = process.argv.slice(2);

function md(descs) {
  const L = ["# Element catalog", "", `Generated by \`npm run elements -- export\` from the code, schema/types.json, the specs and modules/elements/overlay.json. ${descs.length} elements.`, ""];
  for (const kind of E.KINDS) {
    const ds = descs.filter((d) => d.kind === kind); if (!ds.length) continue;
    L.push(`## ${kind} (${ds.length})`, "");
    for (const d of ds) {
      const c = E.completeness(d);
      L.push(`### ${d.id}`, "", d.description || "_No description._", "", `- **Grain:** ${(d.grain && d.grain.statement) || "—"}`, `- **Keys:** surrogate ${(d.keys && d.keys.surrogate) || "none"}; primary ${(d.keys && d.keys.primary || []).join(", ") || "—"}; natural ${((d.keys && d.keys.natural) || []).map((k) => `(${k.join(", ")})`).join(" ") || "—"}`,
        `- **Lifecycle:** ${(d.lifecycle && d.lifecycle.persistence) || "—"}${d.lifecycle && d.lifecycle.retention ? ` (${d.lifecycle.retention})` : ""}`, ...(d.series && d.series.time ? [`- **Series:** ${d.series.time}, ${d.series.cadence || "event"}${d.series.retention ? `, ${d.series.retention}` : ""}`] : []),
        ...((d.relationships || []).length ? [`- **Relationships:** ${d.relationships.map((r) => `${r.rel} ${r.direction === "in" ? "←" : "→"} ${r.target} (${r.cardinality || "?"}${r.onDelete ? `, on delete ${r.onDelete}` : ""}${r.acyclic ? ", acyclic" : ""})`).join("; ")}`] : []),
        `- **Aliases:** ${(d.aliases || []).join(", ") || "—"} · **Tags:** ${(d.tags || []).join(", ") || "—"} · **Completeness:** ${c.score}${c.missing.length ? ` (missing ${c.missing.join(", ")})` : ""}`, "");
      if (Object.keys(d.properties || {}).length) { L.push("| Property | Type | Required | Notes |", "| --- | --- | --- | --- |"); for (const [n, p] of Object.entries(d.properties)) L.push(`| ${n} | ${p.type}${p.unit ? ` (${p.unit})` : ""} | ${p.required ? "yes" : ""} | ${String(p.description || "").replace(/\|/g, "\\|")}${p.enum ? ` One of: ${p.enum.join(", ")}.` : ""}${p.inferred ? " _(inferred from the name)_" : ""} |`); L.push(""); }
    }
  }
  return L.join("\n");
}

(async () => {
  if (cmd === "check-vibe") {
    const dir = path.resolve(arg || "."), r = V.read(dir), ds = V.descriptors(r.vocabulary), S = require("../modules/graph/shacl");
    let bad = 0;
    for (const d of ds) {
      const rows = d.id.endsWith("project") ? r.projects : r.prompts, probs = E.checkRows(d, rows, { lookup: (t, v) => t !== "collection:vibe-project" || r.projects.some((p) => p.folder === v) });
      const quads = rows.flatMap((x) => E.rowToQuads(d, x).quads.map((q) => q.replace(/ <urn:si:data:[^>]+> \.$/, " ."))), v = S.validate(S.loadShapes(E.toShacl([{ ...d, relationships: [] }])), quads.join("\n"));
      console.log(`${d.id}: ${rows.length} rows, ${probs.length} key/grain/vocabulary problems, SHACL ${v.conforms ? "conforms" : `${v.results.length} violations`}`);
      for (const p of probs.slice(0, 40)) console.log(`  - ${p.message}${p.row !== null && rows[p.row] ? ` (${rows[p.row].folder || `${rows[p.row].project} prompt ${rows[p.row].number}`})` : ""}`);
      bad += probs.length;
    }
    process.exitCode = bad ? 1 : 0; return;
  }
  const { boot, db } = require("../server"); await boot();
  const M = require("../modules/elements/module").lib, k = await M.catalog({ db });
  if (cmd === "get") { const id = k.byId.has(arg) ? arg : k.aliases.resolve(arg); console.log(id ? JSON.stringify({ ...k.byId.get(id), completeness: E.completeness(k.byId.get(id)) }, null, 1) : `No element is called ${arg}.`); }
  else if (cmd === "export") {
    const dir = path.resolve(arg || path.join(__dirname, "..", "out", "elements")); fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "elements.jsonld"), JSON.stringify(E.toJsonLd(k.descs), null, 1));
    fs.writeFileSync(path.join(dir, "shapes.ttl"), E.toShacl(k.descs));
    fs.writeFileSync(path.join(dir, "elements.nq"), E.toQuads(k.descs).join("\n") + "\n");
    fs.writeFileSync(path.join(dir, "catalog.md"), md(k.descs));
    console.log(`elements: wrote ${k.descs.length} elements to ${path.relative(process.cwd(), dir) || dir} (elements.jsonld, shapes.ttl, elements.nq, catalog.md)`);
  } else {
    const comp = k.descs.map((d) => ({ id: d.id, ...E.completeness(d) })), g = E.dag(k.descs), by = {};
    for (const d of k.descs) by[d.kind] = (by[d.kind] || 0) + 1;
    console.log(`elements: ${k.descs.length} (${Object.entries(by).map(([a, b]) => `${b} ${a}`).join(", ")}); mean completeness ${(comp.reduce((s, x) => s + x.score, 0) / comp.length).toFixed(3)}; ${comp.filter((x) => x.score === 1).length} complete`);
    console.log(`  DAG of acyclic relations: ${g.violations.length ? `${g.violations.length} violations` : "holds"}; ${g.dangling.length} dangling; invalid ${k.invalid.length}; overlay ids matching nothing ${k.unknownOverlay.length}; alias conflicts ${k.aliases.conflicts.length}`);
    for (const c of comp.filter((x) => x.score < 1).sort((a, b) => a.score - b.score).slice(0, 12)) console.log(`  ${c.score.toFixed(2)} ${c.id}: missing ${c.missing.join(", ")}`);
    for (const c of k.aliases.conflicts.slice(0, 8)) console.log(`  alias "${c.alias}" claimed by ${c.ids.join(" and ")}`);
  }
  if (db.end) await db.end(); process.exit(0);
})().catch((e) => { console.error(`elements: ${e.message}`); process.exit(1); });
