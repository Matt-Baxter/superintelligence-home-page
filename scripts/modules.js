#!/usr/bin/env node
// Module tooling for the modular monolith.
//   node scripts/modules.js gen     write client/blocks.gen.jsx (browser block registry) and copy module pages to public/m/
//   node scripts/modules.js check   boot the kernel and validate every enabled module, block, judge and view (preflight runs this)
//   node scripts/modules.js list    print modules, extension points and contributions
const fs = require("node:fs"), path = require("node:path");
const root = path.resolve(__dirname, "..");
const { createKernel, readEnabled, MODULES_DIR } = require("../kernel/kernel");

function blockDirs(enabled = readEnabled()) {
  const out = [];
  for (const id of enabled) {
    const dir = path.join(MODULES_DIR, id, "blocks");
    if (!fs.existsSync(dir)) continue;
    for (const name of fs.readdirSync(dir).sort()) if (fs.existsSync(path.join(dir, name, "block.mjs"))) out.push({ module: id, name, dir: path.join(dir, name) });
  }
  return out;
}

function gen() {
  const blocks = blockDirs();
  const rel = (p) => "../" + path.relative(root, p).split(path.sep).join("/");
  const lines = ["// Generated by `node scripts/modules.js gen` (part of npm run build). Do not edit; add blocks to modules/<id>/blocks/.", ""];
  blocks.forEach((b, i) => lines.push(`import d${i} from "${rel(path.join(b.dir, "block.mjs"))}";`, `import r${i} from "${rel(path.join(b.dir, "render.jsx"))}";`));
  lines.push("", "export const blocks = [", ...blocks.map((b, i) => `  { module: "${b.module}", def: d${i}, render: r${i} },`), "];", "");
  fs.writeFileSync(path.join(root, "client", "blocks.gen.jsx"), lines.join("\n"));
  // Pages: modules/<id>/pages/x.html → public/m/x.html (Vercel serves public/ from its CDN; locally the kernel serves them too).
  const out = path.join(root, "public", "m"); fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
  const seen = new Map(); let pages = 0;
  for (const id of readEnabled()) {
    const dir = path.join(MODULES_DIR, id, "pages"); if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir)) {
      if (seen.has(f)) throw new Error(`Page ${f} is in both ${seen.get(f)} and ${id}`);
      seen.set(f, id); fs.copyFileSync(path.join(dir, f), path.join(out, f)); pages++;
    }
  }
  return { blocks: blocks.length, pages };
}

async function check() {
  const problems = [], p = (m) => problems.push(m);
  let k;
  try { k = createKernel(); } catch (e) { return [e.message]; }
  for (const m of k.modules) {
    if (!/^[a-z][a-z0-9-]*$/.test(m.id)) p(`module ${m.id}: id must be lowercase-kebab`);
    if (!/^\d+\.\d+\.\d+$/.test(m.version)) p(`module ${m.id}: version must be semver`);
    if (!fs.existsSync(path.join(m.dir, "README.md"))) p(`module ${m.id}: add a README.md (what it does, its extension points, its routes and pages)`);
    // Boundaries: a module may require core (lib/, kernel/, views/) but never another module's files.
    for (const f of walk(m.dir).filter((f) => /\.(m?js|jsx)$/.test(f))) {
      const src = fs.readFileSync(f, "utf8");
      for (const r of src.matchAll(/(?:require\(|from\s+|import\()\s*["']([^"']+)["']/g)) {
        const target = r[1]; if (!target.startsWith(".")) continue;
        const abs = path.resolve(path.dirname(f), target);
        if (abs.startsWith(MODULES_DIR + path.sep) && !abs.startsWith(m.dir + path.sep)) p(`module ${m.id}: ${path.relative(root, f)} imports another module's file (${target}); use an extension point`);
      }
    }
  }
  for (const b of blockDirs()) {
    if (!fs.existsSync(path.join(b.dir, "render.jsx"))) p(`block ${b.name} (${b.module}): missing render.jsx`);
    try { const def = (await import(require("node:url").pathToFileURL(path.join(b.dir, "block.mjs")).href)).default;
      if (def.name !== b.name) p(`block ${b.name}: block.mjs exports name "${def.name}"`);
      if (!def.description || def.description.length < 15) p(`block ${b.name}: needs a description an LLM can use`);
      if (!def.props?.safeParse) p(`block ${b.name}: props must be a zod schema`);
    } catch (e) { p(`block ${b.name}: ${e.message}`); }
  }
  const gen = path.join(root, "client", "blocks.gen.jsx");
  if (!fs.existsSync(gen) || blockDirs().some((b) => !fs.readFileSync(gen, "utf8").includes(`/${b.module}/blocks/${b.name}/block.mjs`))) p("client/blocks.gen.jsx is stale; run npm run build");
  // Views must build and validate (builders that need live data are checked in the browser test instead).
  const { catalog } = await import(require("node:url").pathToFileURL(path.join(root, "views", "catalog.mjs")).href);
  for (const v of k.store.views.values()) {
    if (!v.spec) continue;
    const r = catalog.validate(v.spec); if (!r.success) p(`view ${v.name} (${v.module}): spec doesn't validate against the catalog`);
  }
  const decision = k.modules.find((m) => m.id === "decision");
  if (decision) for (const j of decision.judges.values()) {
    try { const r = j.judge(require(path.join(decision.dir, "sample.json"))); if (!Array.isArray(r.totals) || !("recommendation" in r)) p(`judge ${j.id}: result needs totals and recommendation`); } catch (e) { p(`judge ${j.id}: ${e.message}`); }
  }
  return { problems, k };
}
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);

(async () => {
  const cmd = process.argv[2];
  if (cmd === "gen") { const r = gen(); console.log(`modules: ${r.blocks} blocks, ${r.pages} pages generated`); }
  else if (cmd === "check") {
    const r = await check(); const problems = Array.isArray(r) ? r : r.problems;
    if (problems.length) { console.error(problems.map((x) => "  - " + x).join("\n")); process.exit(1); }
    const d = r.k.describe();
    console.log(`${d.modules.length} modules, ${d.points.length} extension points, ${blockDirs().length} blocks, ${d.views.length} views OK`);
  } else if (cmd === "list") { console.log(JSON.stringify(createKernel().describe(), null, 2)); }
  else { console.log("usage: node scripts/modules.js gen|check|list"); process.exit(1); }
})().catch((e) => { console.error(e.message); process.exit(1); });
