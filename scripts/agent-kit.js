#!/usr/bin/env node
// Agent kit tooling. One source (agent-kit/), many runtimes.
//   node scripts/agent-kit.js sync     rewrite the skill index in CLAUDE.md and AGENTS.md from the SKILL.md files
//   node scripts/agent-kit.js check    validate the kit (preflight runs this): structure, sizes, links, index, manifests, MCP handshake
//   node scripts/agent-kit.js export   build dist/agent-kit/: plugin zip, per-skill zips, one-file bundle, Cursor rule, MCP client configs
const fs = require("node:fs"), path = require("node:path"), { execSync, spawnSync } = require("node:child_process");
const root = path.resolve(__dirname, ".."), KIT = path.join(root, "agent-kit"), SKILLS = path.join(KIT, "skills"), AGENTS = path.join(KIT, "agents");
const read = (p) => fs.readFileSync(p, "utf8");
const fm = (text) => { const m = text.match(/^---\n([\s\S]*?)\n---\n?/); const meta = {}; if (m) for (const l of m[1].split("\n")) { const i = l.indexOf(":"); if (i > 0) meta[l.slice(0, i).trim()] = l.slice(i + 1).trim(); } return { meta, body: m ? text.slice(m[0].length) : text }; };
const skills = () => fs.readdirSync(SKILLS).filter((d) => fs.existsSync(path.join(SKILLS, d, "SKILL.md"))).sort().map((dir) => {
  const text = read(path.join(SKILLS, dir, "SKILL.md")), { meta, body } = fm(text), refDir = path.join(SKILLS, dir, "references");
  return { dir, ...meta, body, lines: text.split("\n").length, refs: fs.existsSync(refDir) ? fs.readdirSync(refDir).sort() : [] };
});
const agents = () => fs.existsSync(AGENTS) ? fs.readdirSync(AGENTS).filter((f) => f.endsWith(".md")).sort().map((f) => ({ file: f, ...fm(read(path.join(AGENTS, f))).meta })) : [];

// ---------- index ----------
const START = "<!-- agent-kit:index:start (generated by `npm run kit:sync`; edit the SKILL.md files instead) -->", END = "<!-- agent-kit:index:end -->";
const short = (d) => d.replace(/\s+/g, " ").replace(/\|/g, "/");
function indexBlock(prefix) {
  const rows = skills().map((s) => `| [${s.name}](${prefix}${s.dir}/SKILL.md) | ${short(s.description)} |`);
  const ag = agents().map((a) => `| ${a.name} | ${short(a.description)} |`);
  return [START, "", "| Skill | Use it when |", "| --- | --- |", ...rows, "", "| Subagent | Does |", "| --- | --- |", ...ag, "", END].join("\n");
}
function withIndex(file, prefix) {
  const text = read(file), a = text.indexOf(START), b = text.indexOf(END);
  if (a < 0 || b < 0) throw new Error(`${path.relative(root, file)} has no agent-kit index markers`);
  return text.slice(0, a) + indexBlock(prefix) + text.slice(b + END.length);
}
const INDEXED = [[path.join(root, "CLAUDE.md"), "agent-kit/skills/"], [path.join(root, "AGENTS.md"), "agent-kit/skills/"]];

// ---------- check ----------
function check() {
  const problems = [];
  const p = (m) => problems.push(m);
  const list = skills();
  if (!list.length) p("no skills found in agent-kit/skills");
  for (const s of list) {
    const where = `skill ${s.dir}`;
    if (s.name !== s.dir) p(`${where}: frontmatter name "${s.name}" must match its folder`);
    if (!/^[a-z0-9-]{1,64}$/.test(s.dir)) p(`${where}: name must be lowercase-kebab, at most 64 characters`);
    if (!s.description) p(`${where}: missing description`);
    else { if (s.description.length > 1024) p(`${where}: description over 1024 characters`); if (!/\buse\b/i.test(s.description)) p(`${where}: description should say when to use it ("Use when …")`); }
    if (s.lines > 80) p(`${where}: SKILL.md is ${s.lines} lines; keep it under 80 and move detail to references/`);
    for (const r of s.refs) if (!s.body.includes(`references/${r}`)) p(`${where}: references/${r} is never mentioned in SKILL.md, so no agent will find it`);
    for (const m of s.body.matchAll(/references\/([\w.-]+\.md)/g)) if (!s.refs.includes(m[1])) p(`${where}: mentions references/${m[1]}, which doesn't exist`);
    for (const m of s.body.matchAll(/\b([a-z]+(?:-[a-z]+)+) skill\b/g)) if (!list.some((x) => x.name === m[1])) p(`${where}: points to a "${m[1]}" skill that doesn't exist`);
  }
  for (const a of agents()) { if (!a.name || !a.description) p(`agent ${a.file}: needs name and description`); }
  for (const [file] of INDEXED) { try { if (read(file) !== withIndex(file, "agent-kit/skills/")) p(`${path.basename(file)}: skill index is stale; run npm run kit:sync`); } catch (e) { p(e.message); } }
  try {
    const plugin = JSON.parse(read(path.join(KIT, ".claude-plugin/plugin.json"))), market = JSON.parse(read(path.join(root, ".claude-plugin/marketplace.json")));
    const entry = market.plugins.find((x) => x.name === plugin.name);
    if (!entry) p("marketplace.json doesn't list the plugin"); else { if (entry.version !== plugin.version) p("plugin version differs between plugin.json and marketplace.json"); if (path.resolve(root, entry.source) !== KIT) p("marketplace source must point at ./agent-kit"); }
    JSON.parse(read(path.join(KIT, "hooks/hooks.json"))); JSON.parse(read(path.join(KIT, ".mcp.json")));
  } catch (e) { p(`manifest: ${e.message}`); }
  // .claude/skills holds one link per kit skill (so other tools, e.g. Spec Kit, can add their own skills beside them).
  for (const s of list) {
    const link = `.claude/skills/${s.dir}`, target = `../../agent-kit/skills/${s.dir}`;
    try { if (fs.readlinkSync(path.join(root, link)) !== target) p(`${link} should link to ${target}`); } catch { p(`${link} should be a symlink to ${target} (run npm run kit:sync; on Windows set git config core.symlinks true)`); }
  }
  try { if (fs.readlinkSync(path.join(root, ".claude/agents")) !== "../agent-kit/agents") p(".claude/agents should link to ../agent-kit/agents"); } catch { p(".claude/agents should be a symlink to ../agent-kit/agents"); }
  const r = spawnSync("node", [path.join(KIT, "mcp/server.js")], { input: '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{}}\n{"jsonrpc":"2.0","id":2,"method":"tools/list"}\n', env: { ...process.env, SI_REPO: root }, timeout: 5000 });
  const out = String(r.stdout || "");
  if (!out.includes('"serverInfo"') || !out.includes('"analyze_text"')) p(`MCP server didn't answer initialize and tools/list${r.stderr?.length ? ": " + String(r.stderr).slice(0, 160) : ""}`);
  return { problems, count: list.length, agents: agents().length };
}

// ---------- export ----------
function exportKit() {
  const out = path.join(root, "dist", "agent-kit"); fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(path.join(out, "skills"), { recursive: true });
  const zip = (cwd, name, what) => execSync(`zip -qr -X "${name}" ${what} -x "*.DS_Store"`, { cwd });
  // 1. Whole plugin, for `/plugin install` from a local path or for sharing.
  zip(root, path.join(out, "si-homepage-kit-plugin.zip"), "agent-kit");
  // 2. One zip per skill (folder with SKILL.md at its top), for uploading as a skill in Claude apps or the API.
  for (const s of skills()) zip(SKILLS, path.join(out, "skills", `${s.dir}.zip`), s.dir);
  // 3. One-file bundle for tools without skills support (v0 project instructions, any chat): index first, details after.
  const list = skills();
  const bundle = [`# Superintelligence Homepage agent kit (v${JSON.parse(read(path.join(KIT, ".claude-plugin/plugin.json"))).version})`, "",
    "Read the index, then only the skill that fits the task, and its references only when the skill says to.", "",
    read(path.join(root, "AGENTS.md")).split(START)[0].replace(/^# .*\n/, "").trim(), "", "## Index", "", ...list.map((s) => `- **${s.name}**: ${s.description}`), "",
    ...list.flatMap((s) => [`---`, ``, `## Skill: ${s.name}`, ``, s.body.trim(), ``, ...s.refs.flatMap((r) => [`### ${s.name} › references/${r}`, ``, read(path.join(SKILLS, s.dir, "references", r)).replace(/^# .*\n/, "").trim(), ``])])].join("\n");
  fs.writeFileSync(path.join(out, "agent-kit.md"), bundle);
  // 4. Cursor rule: always-on index that points at the skill files in the repo.
  fs.mkdirSync(path.join(out, "cursor"), { recursive: true });
  fs.writeFileSync(path.join(out, "cursor", "si-homepage.mdc"), `---\ndescription: Superintelligence Homepage rules and skill index\nalwaysApply: true\n---\n\n${read(path.join(root, "AGENTS.md")).replace(/^# .*\n/, "").trim()}\n`);
  // 5. MCP client configs (the server gives skills and app tools to any MCP client).
  const server = { command: "node", args: ["<path to clone>/agent-kit/mcp/server.js"], env: { SI_REPO: "<path to clone>" } };
  fs.writeFileSync(path.join(out, "mcp-configs.json"), JSON.stringify({
    "claude-desktop (claude_desktop_config.json)": { mcpServers: { "si-homepage": server } },
    "claude-code (.mcp.json in another project, or: claude mcp add si-homepage -- node <path>/agent-kit/mcp/server.js)": { mcpServers: { "si-homepage": server } },
    "cursor (.cursor/mcp.json)": { mcpServers: { "si-homepage": server } },
    "vscode (.vscode/mcp.json)": { servers: { "si-homepage": { type: "stdio", ...server } } },
  }, null, 2) + "\n");
  return out;
}

const cmd = process.argv[2];
if (cmd === "sync") {
  for (const [file, prefix] of INDEXED) fs.writeFileSync(file, withIndex(file, prefix));
  const dir = path.join(root, ".claude", "skills"); fs.mkdirSync(dir, { recursive: true });
  for (const s of skills()) { const link = path.join(dir, s.dir); if (!fs.existsSync(link)) fs.symlinkSync(`../../agent-kit/skills/${s.dir}`, link); } console.log(`index updated: ${skills().length} skills, ${agents().length} subagents`); }
else if (cmd === "check") { const r = check(); if (r.problems.length) { console.error(r.problems.map((x) => "  - " + x).join("\n")); process.exit(1); } console.log(`${r.count} skills, ${r.agents} subagents, plugin, hooks and MCP server OK`); }
else if (cmd === "export") { const out = exportKit(); console.log("exported to " + path.relative(root, out)); for (const f of execSync("find . -type f | sort", { cwd: out }).toString().trim().split("\n")) console.log("  " + f.slice(2) + "  " + fs.statSync(path.join(out, f)).size + " B"); }
else { console.log("usage: node scripts/agent-kit.js sync|check|export"); process.exit(1); }
