#!/usr/bin/env node
// OpenSpec beside Spec Kit. Spec Kit (specs/NNN-*/spec.md) stays the source of truth for REQ-001..REQ-060; this script
// writes them as OpenSpec capability specs (openspec/specs/<capability>/spec.md) using openspec/capabilities.json, so
// OpenSpec tooling and agents see the whole system. New work is planned as OpenSpec changes (openspec/changes/<id>/:
// proposal, design, tasks and spec deltas) that cite their REQ ids.
//
//   node scripts/openspec.js sync     write openspec/specs from specs/ (generated: edit specs/ or capabilities.json)
//   node scripts/openspec.js check    exit 1 if a generated spec is stale, a REQ isn't mapped, or a change is malformed
//   npx @fission-ai/openspec validate --all   (optional) the OpenSpec CLI's own validator
const fs = require("node:fs"), path = require("node:path");
const root = path.join(__dirname, ".."), OS = path.join(root, "openspec");
const S = require("../modules/project/specs");
const CAPS = require("../openspec/capabilities.json"), MAP = CAPS.capabilities;
// REQs planned in an open change: covered by the change's spec deltas until it is archived.
const IN_CHANGES = new Set(Object.entries(CAPS.inChanges || {}).filter(([k]) => k !== "about").flatMap(([, v]) => v));

// A short requirement name: the words after the modal verb ("MUST show a feed of ..." -> "Show a feed of ...").
const shortName = (text) => {
  const t = String(text).replace(/^In the extended version, /i, ""), m = t.match(/\b(MUST NOT|MUST|SHOULD|MAY)\b\s+(?:be able to\s+)?(.*)/s);
  const rest = m ? `${m[1] === "MUST NOT" ? "Not " : ""}${m[2]}` : t;
  const first = rest.split(/[,;:(]| and (?=[a-z]+ )/)[0].trim().replace(/\.$/, "");
  const words = first.split(/\s+/).slice(0, 9).join(" ");
  return words.charAt(0).toUpperCase() + words.slice(1);
};
const keyOf = (r, dupes) => (dupes.has(r.id) ? `${r.spec}:${r.id}` : r.id);

function build() {
  const { reqs } = S.collect();
  const counts = reqs.reduce((m, r) => m.set(r.id, (m.get(r.id) || 0) + 1), new Map()), dupes = new Set([...counts].filter(([, n]) => n > 1).map(([id]) => id));
  const byKey = new Map(reqs.map((r) => [keyOf(r, dupes), r]));
  const mapped = new Set([...Object.values(MAP).flatMap((c) => c.reqs), ...IN_CHANGES]);
  const problems = [...byKey.keys()].filter((k) => !mapped.has(k)).map((k) => `${k} isn't in any capability (openspec/capabilities.json)`);
  for (const [ch, ids] of Object.entries(CAPS.inChanges || {})) if (ch !== "about" && !fs.existsSync(path.join(OS, "changes", ch))) problems.push(`inChanges names ${ch}, which isn't an open change`);
  problems.push(...[...mapped].filter((k) => !byKey.has(k)).map((k) => `capabilities.json names ${k}, which no spec defines`));
  const files = {};
  for (const [cap, c] of Object.entries(MAP)) {
    const L = [`# ${c.title} Specification`, "", `<!-- Generated by scripts/openspec.js from specs/ (Spec Kit is the source of truth for these requirements). Edit specs/NNN-*/spec.md or openspec/capabilities.json, then run: node scripts/openspec.js sync -->`, "", "## Purpose", "", c.purpose, "", "## Requirements", ""];
    for (const k of c.reqs) {
      const r = byKey.get(k); if (!r) continue;
      const status = r.status === "approved" ? "approved (shared spec)" : "proposed, not approved: needs both partners";
      L.push(`### Requirement: ${r.id}${dupes.has(r.id) ? ` (spec ${r.spec})` : ""} ${shortName(r.text)}`, r.text, "", `Source: \`specs/${S.collect().specs.find((s) => s.id === r.spec)?.dir || r.spec}/spec.md\`, ${status}.${r.trace ? ` Code: ${r.trace.code}.` : ""}`, "");
      L.push(`#### Scenario: ${r.id} is checked`, r.trace ? `- **WHEN** the checks named in docs/SPEC_TRACE.md run (${r.trace.check.replace(/\n/g, " ")})` : "- **WHEN** a person checks it (no automated check is traced yet)", r.trace ? "- **THEN** they pass, as preflight and the browser test require" : "- **THEN** they record the result in the project tracker", "");
    }
    files[`specs/${cap}/spec.md`] = L.join("\n");
  }
  return { files, problems };
}

// Structure of a change: proposal (Why, What Changes, Impact), tasks (numbered checkboxes), and spec deltas whose
// requirements carry SHALL or MUST and at least one scenario each.
function checkChanges() {
  const dir = path.join(OS, "changes"), problems = [];
  if (!fs.existsSync(dir)) return problems;
  for (const id of fs.readdirSync(dir).filter((d) => d !== "archive" && fs.statSync(path.join(dir, d)).isDirectory())) {
    const p = (f) => path.join(dir, id, f), read = (f) => (fs.existsSync(p(f)) ? fs.readFileSync(p(f), "utf8") : null);
    const prop = read("proposal.md"), tasks = read("tasks.md");
    if (!prop) { problems.push(`${id}: no proposal.md`); continue; }
    for (const h of ["## Why", "## What Changes", "## Impact"]) if (!prop.includes(h)) problems.push(`${id}: proposal.md has no "${h}"`);
    if (!tasks || !/^- \[[ x]\] \d+\.\d+ /m.test(tasks)) problems.push(`${id}: tasks.md has no numbered checkbox tasks`);
    const sd = p("specs");
    if (!fs.existsSync(sd)) { problems.push(`${id}: no spec deltas (specs/<capability>/spec.md)`); continue; }
    for (const cap of fs.readdirSync(sd)) {
      const md = fs.readFileSync(path.join(sd, cap, "spec.md"), "utf8");
      if (!/^## (ADDED|MODIFIED|REMOVED|RENAMED) Requirements/m.test(md)) problems.push(`${id}/${cap}: no ADDED/MODIFIED/REMOVED section`);
      for (const block of md.split(/^### Requirement: /m).slice(1)) {
        const name = block.split("\n")[0], body = block.split(/^#### Scenario:/m)[0];
        if (!/\b(SHALL|MUST)\b/.test(body)) problems.push(`${id}/${cap}: "${name}" has no SHALL or MUST`);
        if (!/^#### Scenario: /m.test(block)) problems.push(`${id}/${cap}: "${name}" has no scenario`);
        else for (const sc of block.split(/^#### Scenario: /m).slice(1)) if (!/- \*\*WHEN\*\*/.test(sc) || !/- \*\*THEN\*\*/.test(sc)) problems.push(`${id}/${cap}: a scenario of "${name}" lacks WHEN or THEN`);
      }
    }
  }
  return problems;
}

const cmd = process.argv[2] || "check";
const { files, problems } = build();
if (cmd === "sync") {
  for (const [f, text] of Object.entries(files)) { fs.mkdirSync(path.dirname(path.join(OS, f)), { recursive: true }); fs.writeFileSync(path.join(OS, f), text); }
  console.log(`openspec: wrote ${Object.keys(files).length} capability specs`);
}
const stale = Object.entries(files).filter(([f, text]) => !fs.existsSync(path.join(OS, f)) || fs.readFileSync(path.join(OS, f), "utf8") !== text).map(([f]) => f);
const all = [...problems, ...stale.map((f) => `openspec/${f} is stale (node scripts/openspec.js sync)`), ...checkChanges()];
const changes = fs.existsSync(path.join(OS, "changes")) ? fs.readdirSync(path.join(OS, "changes")).filter((d) => d !== "archive").length : 0;
if (all.length) { console.log(`openspec: ${all.length} problem(s)\n  ${all.join("\n  ")}`); process.exit(1); }
console.log(`openspec: ${Object.keys(files).length} capability specs current, ${changes} open change(s) well-formed`);
module.exports = { build, checkChanges };
