// The system as a typed graph (REQ-065, proposed; openspec/changes/add-graph-model-and-flywheel). Generated from the
// kernel, the data registry, the code map, Spec Kit, the agent kit, CLAUDE.md's hard rules, the learnings ledger and
// the QA checks; never edited by hand. Nodes: { id, type, label, props }; edges: { s, p, o } (directed).
const fs = require("node:fs"), path = require("node:path");
const ROOT = path.join(__dirname, "..", "..");
const NS = "https://superintelligence-homepage.example/ns#";
const TYPES = ["Module", "ExtensionPoint", "Block", "Source", "Action", "Page", "Route", "Table", "Requirement", "Capability", "Skill", "Standard", "Learning", "Check", "View"];

function build({ enabled } = {}) {
  const nodes = new Map(), edges = [];
  const node = (type, key, label, props = {}) => { const id = `${type.toLowerCase()}:${key}`; if (!nodes.has(id)) nodes.set(id, { id, type, label: String(label || key), props }); else Object.assign(nodes.get(id).props, props); return id; };
  const edge = (s, p, o) => { if (s && o) edges.push({ s, p, o }); };

  // Modules, points, contributions, views (the kernel), sources and actions (the data registry, filled in setup).
  const { createKernel } = require("../../kernel/kernel");
  // The whole system, whatever profile this process runs: every module in modules.json.
  const all = JSON.parse(fs.readFileSync(path.join(ROOT, "modules", "modules.json"), "utf8")).enabled;
  const k = createKernel({ enabled: enabled || all });
  for (const m of k.modules) { const id = node("Module", m.id, m.id, { version: m.version, about: m.description || "" }); for (const r of m.requires || []) edge(id, "requires", node("Module", r, r)); }
  for (const [pid, p] of k.points) { const id = node("ExtensionPoint", pid, pid, { owner: p.owner }); edge(id, "ownedBy", p.owner === "kernel" ? node("Module", "kernel", "kernel") : node("Module", p.owner, p.owner)); for (const c of p.contributions) edge(node("Module", c.module, c.module), "contributes", id); }
  for (const [name, v] of k.store.views) edge(node("Module", v.module, v.module), "owns", node("View", name, v.title, { admin: !!v.admin }));
  const reg = require("../data/registry");
  for (const d of reg.sources.values()) edge(node("Module", d.module, d.module), "owns", node("Source", d.id, d.id, { access: d.access, about: d.about }));
  for (const d of reg.actions.values()) edge(node("Module", d.module, d.module), "owns", node("Action", d.id, d.id, { access: d.access, about: d.about }));
  for (const m of k.modules) { const dir = path.join(ROOT, "modules", m.id, "blocks"); if (fs.existsSync(dir)) for (const b of fs.readdirSync(dir).filter((x) => fs.existsSync(path.join(dir, x, "block.mjs")))) edge(node("Module", m.id, m.id), "owns", node("Block", b, b)); }

  // Pages, routes, tables and their calls, reads and writes (the code map, regenerated by npm run build).
  const cmFile = path.join(ROOT, "modules", "codemap", "data", "codemap.json");
  if (fs.existsSync(cmFile)) {
    const cm = JSON.parse(fs.readFileSync(cmFile, "utf8")), keep = { page: "Page", route: "Route", table: "Table" }, ids = new Map();
    for (const n of cm.nodes) if (keep[n.kind]) { const id = node(keep[n.kind], n.id.slice(n.kind.length + 1), n.label, n.module ? { module: n.module } : {}); ids.set(n.id, id); if (n.module && n.module !== "core") edge(node("Module", n.module, n.module), "owns", id); }
    for (const e of cm.edges) if (ids.has(e.from) && ids.has(e.to) && ["calls", "reads", "writes"].includes(e.kind)) edge(ids.get(e.from), e.kind, ids.get(e.to));
  }

  // Requirements and their traces (Spec Kit), capabilities (OpenSpec), skills (the agent kit), hard rules, learnings, QA checks.
  const S = require("../project/specs"), { reqs } = S.collect();
  // Optional on a deployment that bundles only modules/** (Vercel): each section is skipped when its files are absent.
  const readJson = (f) => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8")); } catch { return null; } };
  const caps = readJson("openspec/capabilities.json") || { capabilities: {} };
  for (const r of reqs) {
    const id = node("Requirement", `${r.spec}-${r.id}`, r.id, { spec: r.spec, level: r.level, status: r.status, traced: !!r.trace });
    if (r.trace) {
      const mods = [...new Set((r.trace.code.match(/modules\/([a-z0-9-]+)/g) || []).map((x) => x.slice(8)))];
      for (const m of mods) if (nodes.has(`module:${m}`)) edge(id, "tracedTo", `module:${m}`);
      const check = node("Check", `trace:${r.spec}-${r.id}`, r.trace.check.slice(0, 120), { kind: "trace" }); edge(id, "checkedBy", check);
    }
  }
  for (const [cid, c] of Object.entries(caps.capabilities)) { const id = node("Capability", cid, c.title); for (const k2 of c.reqs) { const [sp, rid] = k2.includes(":") ? k2.split(":") : [null, k2]; const r = reqs.find((x) => x.id === rid && (!sp || x.spec === sp)); if (r) edge(id, "includes", `requirement:${r.spec}-${r.id}`); } }
  const skills = path.join(ROOT, "agent-kit", "skills");
  if (fs.existsSync(skills)) for (const s of fs.readdirSync(skills).filter((x) => fs.existsSync(path.join(skills, x, "SKILL.md")))) {
    const text = fs.readFileSync(path.join(skills, s, "SKILL.md"), "utf8"), id = node("Skill", s, s, { about: (text.match(/^description:\s*(.*)$/m) || [])[1] || "" });
    // A skill is about the modules and requirements it names.
    for (const m of new Set((text.match(/modules\/([a-z0-9-]+)/g) || []).map((x) => x.slice(8)))) if (nodes.has(`module:${m}`)) edge(id, "about", `module:${m}`);
    for (const r of new Set(text.match(/REQ-\d{3}/g) || [])) { const hit = reqs.find((x) => x.id === r); if (hit) edge(id, "about", `requirement:${hit.spec}-${hit.id}`); }
  }
  const claude = fs.existsSync(path.join(ROOT, "CLAUDE.md")) ? fs.readFileSync(path.join(ROOT, "CLAUDE.md"), "utf8") : "", hard = (claude.split("## Hard rules")[1] || "").split("\n## ")[0];
  for (const m of hard.matchAll(/^- \*\*([^*]+)\*\*\s*(.*)$/gm)) node("Standard", m[1].replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "").toLowerCase(), m[1].replace(/\.$/, ""), { text: m[2].slice(0, 300) });
  const QA = require("../responses/qa");
  for (const q of Object.keys(QA.CHECKS)) edge(node("Module", "responses", "responses"), "owns", node("Check", `qa:${q}`, `qa ${q}`, { kind: "qa" }));
  const req060 = reqs.find((x) => x.id === "REQ-060"), AREA = { learning: "lab", planning: "lab" };
  for (const l of require("../responses/learnings.json").learnings) {
    const id = node("Learning", l.id, `${l.id} ${l.symptom.slice(0, 60)}`, { area: l.area, cause: l.cause, fix: l.fix, guard: l.guard, found: l.found });
    const [kind, name] = [l.guard.split(":")[0], l.guard.slice(l.guard.indexOf(":") + 1)];
    edge(id, "guardedBy", kind === "qa" ? `check:qa:${name}` : node("Check", `unit:${name}`, name.slice(0, 120), { kind: "unit" }));
    // Every learning so far came from paper responses (REQ-060); its area says which module it changed.
    if (req060) edge(id, "serves", `requirement:${req060.spec}-${req060.id}`);
    edge(id, "about", `module:${AREA[l.area] || "responses"}`);
  }
  return { nodes: [...nodes.values()], edges, types: TYPES };
}

// As RDF: urn:si:app:<type>:<key> nodes, si: classes and properties, labels.
function triples({ nodes, edges }) {
  const KG = require("../data/kg"), I = (id) => KG.iri(`urn:si:app:${id.replace(/[^A-Za-z0-9:._~-]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase().padStart(2, "0")}`)}`), L = [];
  for (const n of nodes) {
    L.push(`${I(n.id)} ${KG.A} ${KG.si(n.type)} .`, `${I(n.id)} ${KG.LABEL} ${KG.lit(n.label)} .`);
    for (const [k, v] of Object.entries(n.props || {})) if (v !== undefined && v !== null && v !== "") L.push(`${I(n.id)} ${KG.si(k)} ${typeof v === "boolean" ? KG.lit(v, "bool") : KG.lit(String(v).slice(0, 500))} .`);
  }
  for (const e of edges) L.push(`${I(e.s)} ${KG.si(e.p)} ${I(e.o)} .`);
  return L;
}
module.exports = { build, triples, NS, TYPES };
