// Animated explainer for a paper response (REQ-058, proposed), in the math-animation style that Manim Community makes
// (the open-source engine, MIT licence): shapes that move to show a mechanism, bars that grow with their values,
// curves traced by a dot, a checklist that adds up to a score. Our own palette and layouts; no characters or branding
// borrowed from anyone's channel.
//
// Low cost, by design: everything runs on a CPU, off the web server (scripts/respond.js or the Learn worker).
//   1. narration: a local text-to-speech voice per beat (Piper when PIPER_MODEL points at a voice, else espeak-ng,
//      else none: captions only). Each beat lasts as long as its narration, so picture and voice stay in step.
//   2. scene.py: one Manim scene generated from the plan, with each beat's duration baked in.
//   3. captions.srt: the narration, split by sentence and timed within each beat.
//   4. ffmpeg joins picture, voice and a soft subtitle track into video.mp4.
const fs = require("node:fs"), path = require("node:path"), { execFileSync } = require("node:child_process");
const has = (cmd, args = ["--version"]) => { try { execFileSync(cmd, args, { stdio: "ignore", timeout: 60000 }); return true; } catch { return false; } };
const py = (s) => JSON.stringify(String(s));
const PALETTE = { bg: "#14161b", ink: "#e8e6e1", mute: "#8b8f98", backed: "#5fb3a1", described: "#7a9cc6", partly: "#d6b25e", missing: "#6b6f78", bad: "#c96f5a", accent: "#e8e6e1" };
const LEVEL_COLOR = { backed: "backed", described: "described", "partly backed": "partly", "not found in the body": "missing" };

// ---------- narration ----------
function voice() {
  if (process.env.PIPER_MODEL && fs.existsSync(process.env.PIPER_MODEL) && has("piper", ["--help"])) return { id: "piper", label: "Piper (local neural voice)" };
  if (has("espeak-ng")) return { id: "espeak-ng", label: "espeak-ng (local, robotic)" };
  return { id: "none", label: "no voice installed: captions only" };
}
function speak(text, file, v) {
  if (v.id === "piper") execFileSync("piper", ["--model", process.env.PIPER_MODEL, "--output_file", file], { input: text, timeout: 300000 });
  else if (v.id === "espeak-ng") execFileSync("espeak-ng", ["-v", process.env.ESPEAK_VOICE || "en-us", "-s", process.env.ESPEAK_RATE || "158", "-w", file, text], { timeout: 300000 });
  else return null;
  return file;
}
const duration = (file) => { try { return Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", file]).toString().trim()) || 0; } catch { return 0; } };

// ---------- captions ----------
const ts = (s) => { const ms = Math.round(s * 1000), h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000) % 60, sec = Math.floor(ms / 1000) % 60; return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}:${String(sec).padStart(2, "0")},${String(ms % 1000).padStart(3, "0")}`; };
function captions(beats) {
  const out = []; let t = 0, n = 1;
  for (const b of beats) {
    const parts = b.narration.match(/[^.?!]+[.?!]*/g)?.map((x) => x.trim()).filter(Boolean) || [b.narration];
    // Long sentences become two caption lines of at most ~84 characters each.
    const chunks = parts.flatMap((p) => { if (p.length <= 84) return [p]; const w = p.split(" "), lines = []; let cur = ""; for (const x of w) { if ((cur + " " + x).trim().length > 84) { lines.push(cur); cur = x; } else cur = (cur + " " + x).trim(); } lines.push(cur); return lines; });
    const total = chunks.reduce((s, c) => s + c.length, 0) || 1; let at = t;
    for (const c of chunks) { const d = (b.seconds - 0.3) * (c.length / total); out.push(`${n++}\n${ts(at)} --> ${ts(at + d)}\n${c}\n`); at += d; }
    t += b.seconds;
  }
  return out.join("\n");
}

// ---------- the Manim scene ----------
function scene(p) {
  const L = [], cls = "PaperResponse";
  const P = (s) => L.push("        " + s);
  L.push(`# Generated by modules/responses/video.js for "${p.title.replace(/"/g, "'")}". Render: manim -qm scene.py ${cls}`,
    "from manim import *", "", `PAL = ${JSON.stringify(PALETTE)}`, "",
    "def wrap(s, n=44):", "    words, lines, cur = s.split(), [], ''", "    for w in words:", "        if len(cur) + len(w) + 1 > n: lines.append(cur); cur = w", "        else: cur = (cur + ' ' + w).strip()", "    lines.append(cur)", "    return '\\n'.join(lines)", "",
    "def label(s, size=26, color=None, n=44):", "    return Text(wrap(s, n), font_size=size, color=color or PAL['ink'], line_spacing=0.9)", "",
    "# Counters are plain Text redrawn from a tracker, so rendering needs no LaTeX install.",
    "def counter(tracker, places=0, unit='', size=24):", "    return always_redraw(lambda: Text(f'{tracker.get_value():.{places}f}{unit}', font_size=size, color=PAL['ink']))", "",
    `class ${cls}(Scene):`, "    def hold(self, used, seconds):", "        self.wait(max(0.1, seconds - used))", "",
    "    def clear(self):", "        if self.mobjects: self.play(*[FadeOut(m) for m in self.mobjects], run_time=0.35)", "",
    "    def construct(self):", "        self.camera.background_color = PAL['bg']");
  for (const b of p.beats) {
    const v = b.visual, T = b.seconds;
    L.push(`        # --- ${b.id}: ${b.goal.replace(/\n/g, " ")}`);
    if (v.kind === "title") {
      P(`t = label(${py(v.title)}, 40, n=34); s = label(${py(v.sub)}, 22, PAL['mute']).next_to(t, DOWN, buff=0.4)`);
      P("u = Line(LEFT * 3, RIGHT * 3, color=PAL['mute'], stroke_width=2).next_to(s, DOWN, buff=0.35)");
      P("self.play(Write(t), run_time=1.2); self.play(FadeIn(s, shift=UP * 0.15), Create(u), run_time=0.6)");
      P(`self.hold(1.8 + 0.35, ${T}); self.clear()`);
    } else if (v.kind === "claims") {
      P("rows = VGroup()");
      v.items.forEach((it) => P(`rows.add(VGroup(Dot(radius=0.11, color=PAL[${py(LEVEL_COLOR[it.level] || "missing")}]), label(${py(it.text)}, 24, n=52), label(${py(it.level)}, 18, PAL[${py(LEVEL_COLOR[it.level] || "missing")}])).arrange(RIGHT, buff=0.3))`));
      P("rows.arrange(DOWN, aligned_edge=LEFT, buff=0.5).move_to(ORIGIN)");
      P("head = label('What it claims', 30, PAL['mute']).to_edge(UP, buff=0.6)");
      P("self.play(FadeIn(head), run_time=0.4)");
      P("for r in rows: self.play(GrowFromCenter(r[0]), FadeIn(r[1], shift=RIGHT * 0.2), FadeIn(r[2]), run_time=0.6)");
      P(`self.hold(0.4 + 0.6 * len(rows) + 0.35, ${T}); self.clear()`);
    } else if (v.kind === "flow") {
      P("head = label('How it works', 30, PAL['mute']).to_edge(UP, buff=0.6)");
      P("boxes = VGroup()");
      v.steps.forEach((s) => P(`boxes.add(VGroup(RoundedRectangle(corner_radius=0.18, width=3.4, height=1.7, color=PAL['mute'], stroke_width=2), label(${py(s)}, 22, n=20)))`));
      P("for b in boxes: b[1].scale_to_fit_width(min(b[1].width, b[0].width - 0.4)); b[1].move_to(b[0])");
      P(`boxes.arrange(RIGHT, buff=0.55) if len(boxes) <= 3 else boxes.arrange_in_grid(rows=2, buff=(0.7, 0.6))`);
      P("boxes.scale_to_fit_width(min(boxes.width, 12.5)).move_to(DOWN * 0.3)");
      P("arrows = VGroup(*[Arrow(boxes[i].get_right() if len(boxes) <= 3 or i != 1 else boxes[i].get_bottom(), boxes[i + 1].get_left() if len(boxes) <= 3 or i != 1 else boxes[i + 1].get_top(), buff=0.12, color=PAL['mute'], stroke_width=3) for i in range(len(boxes) - 1)])");
      P("self.play(FadeIn(head), run_time=0.4)");
      P("for i, b in enumerate(boxes):");
      P("    self.play(Create(b[0]), FadeIn(b[1]), run_time=0.5)");
      P("    if i < len(arrows): self.play(GrowArrow(arrows[i]), run_time=0.35)");
      // A dot travels the flow once: the "watch it happen" moment.
      P("dot = Dot(color=PAL['backed'], radius=0.12).move_to(boxes[0].get_bottom() + DOWN * 0.3)");
      P("self.play(FadeIn(dot), run_time=0.2)");
      P("for b in boxes[1:]: self.play(dot.animate.move_to(b.get_bottom() + DOWN * 0.3), run_time=0.45)");
      P(`self.hold(0.4 + 0.85 * len(boxes) + 0.2 + 0.45 * (len(boxes) - 1) + 0.35, ${T}); self.clear()`);
    } else if (v.kind === "bars") {
      const max = Math.max(...v.bars.map((x) => Math.abs(x.value))) || 1;
      P(`head = label(${py(`The paper reports: ${v.metric}`)}, 28, PAL['mute']).to_edge(UP, buff=0.5)`);
      P(`cap = label(${py(`Table ${v.table} of the paper (its numbers, not rerun by us)`)}, 18, PAL['mute']).to_edge(DOWN, buff=0.45)`);
      P("base = Line(LEFT * 5, RIGHT * 5, color=PAL['mute'], stroke_width=2).shift(DOWN * 2)");
      P("self.play(FadeIn(head), Create(base), FadeIn(cap), run_time=0.6)");
      const n = v.bars.length, gap = 10 / n;
      v.bars.forEach((x, i) => {
        const h = (Math.abs(x.value) / max) * 3.6, cx = (-5 + gap * (i + 0.5)).toFixed(2);
        P(`r${i} = Rectangle(width=${(gap * 0.55).toFixed(2)}, height=0.001, fill_opacity=0.85, stroke_width=0, color=PAL['described']).move_to([${cx}, -2, 0], aligned_edge=DOWN)`);
        P(`k${i} = ValueTracker(0); n${i} = always_redraw(lambda r=r${i}, k=k${i}: Text(f"{k.get_value():.${Number.isInteger(x.value) ? 0 : 1}f}${v.unit}", font_size=24, color=PAL['ink']).next_to(r, UP, buff=0.1))`);
        P(`l${i} = label(${py(x.label)}, 20, PAL['mute'], n=14).next_to([${cx}, -2, 0], DOWN, buff=0.2)`);
        P(`self.play(FadeIn(l${i}), FadeIn(n${i}), run_time=0.2)`);
        P(`self.play(r${i}.animate.stretch_to_fit_height(${Math.max(0.02, h).toFixed(3)}, about_edge=DOWN), k${i}.animate.set_value(${x.value}), run_time=0.8)`);
      });
      P(`self.hold(0.6 + 1.0 * ${n} + 0.35, ${T}); self.clear()`);
    } else if (v.kind === "quote") {
      P(`q = label(${py(`“${v.text}”`)}, 28, n=46); src = label(${py(`the paper, ${v.section}`)}, 20, PAL['mute']).next_to(q, DOWN, buff=0.4)`);
      P("bar = Line(UP, DOWN, color=PAL['described'], stroke_width=5).scale_to_fit_height(q.height).next_to(q, LEFT, buff=0.35)");
      P("self.play(Create(bar), Write(q), run_time=1.6); self.play(FadeIn(src), run_time=0.4)");
      P(`self.hold(2.0 + 0.35, ${T}); self.clear()`);
    } else if (v.kind === "checklist") {
      P("head = label('How careful is it?', 30, PAL['mute']).to_edge(UP, buff=0.45)");
      P("rows = VGroup()");
      v.items.forEach((it) => P(`rows.add(VGroup(Text(${py(it.met ? "✓" : "✗")}, font_size=24, color=PAL[${py(it.met ? "backed" : "bad")}]), label(${py(it.label)}, 20, PAL[${py(it.met ? "ink" : "mute")}], n=60), Text(${py(it.met ? `+${it.points}` : "0")}, font_size=18, color=PAL['mute'])).arrange(RIGHT, buff=0.25))`));
      P("rows.arrange(DOWN, aligned_edge=LEFT, buff=0.16).scale_to_fit_height(min(rows.height, 5.2)).move_to(LEFT * 1.6 + DOWN * 0.35)");
      P("track = Rectangle(width=0.5, height=4.6, color=PAL['mute'], stroke_width=2).move_to(RIGHT * 5 + DOWN * 0.35)");
      P("fill = Rectangle(width=0.5, height=0.001, fill_opacity=0.9, stroke_width=0, color=PAL['backed']).move_to(track.get_bottom(), aligned_edge=DOWN)");
      P("k = ValueTracker(0); score = always_redraw(lambda: Text(f'{k.get_value():.0f}', font_size=40, color=PAL['ink']).next_to(track, UP, buff=0.2))");
      P("self.play(FadeIn(head), Create(track), FadeIn(score), run_time=0.5)");
      P("self.play(LaggedStart(*[FadeIn(r, shift=RIGHT * 0.15) for r in rows], lag_ratio=0.12), run_time=min(4, 0.25 * len(rows)))");
      P(`self.play(fill.animate.stretch_to_fit_height(max(0.01, 4.6 * ${v.score} / 100), about_edge=DOWN), k.animate.set_value(${v.score}), run_time=1.2)`);
      P(`self.hold(0.5 + min(4, 0.25 * len(rows)) + 1.2 + 0.35, ${T}); self.clear()`);
    } else if (v.kind === "curve") {
      const pts = v.series.map((s) => s.points.map(([x, y]) => [Number(x), Number(y)]));
      const xs = pts.flat().map((q) => q[0]), ys = pts.flat().map((q) => q[1]);
      const x0 = Math.min(...xs), x1 = Math.max(...xs), y0 = Math.min(0, ...ys), y1 = Math.max(...ys) || 1;
      P(`head = label(${py(`Our toy check: ${v.title}`)}, 26, PAL['mute']).to_edge(UP, buff=0.45)`);
      P(`ax = Axes(x_range=[${x0}, ${x1 || 1}, ${Math.max(1, Math.round((x1 - x0) / 5))}], y_range=[${y0.toFixed(3)}, ${(y1 * 1.1).toFixed(3)}, ${((y1 * 1.1 - y0) / 4 || 1).toFixed(3)}], x_length=9.5, y_length=4.6, axis_config={'color': PAL['mute'], 'include_numbers': False}).move_to(DOWN * 0.3)`);
      P("self.play(FadeIn(head), Create(ax), run_time=0.8)");
      pts.forEach((s, i) => {
        P(`pts${i} = [ax.c2p(x, y) for x, y in ${JSON.stringify(s)}]`);
        P(`c${i} = VMobject(color=PAL[${py(i ? "described" : "backed")}], stroke_width=4).set_points_as_corners(pts${i})`);
        P(`d${i} = Dot(pts${i}[0], color=PAL[${py(i ? "described" : "backed")}])`);
        P(`self.add(d${i}); self.play(Create(c${i}), MoveAlongPath(d${i}, c${i}), run_time=2.2, rate_func=linear)`);
      });
      P(`v = label(${py(v.verdict)}, 24, PAL['backed']).next_to(ax, DOWN, buff=0.2)`);
      P("self.play(FadeIn(v), run_time=0.4)");
      P(`self.hold(1.2 + 2.2 * ${pts.length} + 0.35, ${T}); self.clear()`);
    } else if (v.kind === "questions") {
      P("head = label('Still open', 30, PAL['mute']).to_edge(UP, buff=0.6)");
      P(`qs = VGroup(*[VGroup(Text('?', font_size=34, color=PAL['partly']), label(q, 24, n=56)).arrange(RIGHT, buff=0.3) for q in ${JSON.stringify(v.items)}]).arrange(DOWN, aligned_edge=LEFT, buff=0.5)`);
      P("self.play(FadeIn(head), run_time=0.4)");
      P("for q in qs: self.play(FadeIn(q, shift=UP * 0.15), run_time=0.5)");
      P(`self.hold(0.4 + 0.5 * len(qs) + 0.35, ${T}); self.clear()`);
    } else {
      P(`head = label('Read it yourself', 30, PAL['mute']).to_edge(UP, buff=0.8)`);
      P(`srcs = VGroup(*[label(s, 22, n=64) for s in ${JSON.stringify(v.items || [])}]).arrange(DOWN, buff=0.35)`);
      P("note = label('Our reading of the text, not a peer review.', 20, PAL['mute']).to_edge(DOWN, buff=0.7)");
      P("self.play(FadeIn(head), FadeIn(srcs), FadeIn(note), run_time=0.6)");
      P(`self.hold(0.6, ${T})`);
    }
  }
  return { file: "scene.py", className: cls, source: L.join("\n") + "\n" };
}

// The same beats for the browser explainer player (/m/explainer?r=<slug>), which knows title, say, bars, graph.
function playerStoryboard(p) {
  return { id: `response-${p.slug}`, title: p.title, scenes: p.beats.map((b) => {
    const v = b.visual;
    if (v.kind === "title") return { kind: "title", text: v.title, sub: v.sub, seconds: b.seconds };
    if (v.kind === "bars") return { kind: "bars", title: `The paper reports: ${v.metric} (table ${v.table})`, bars: v.bars.map((x) => ({ label: x.label, value: Math.max(0, Math.min(100, x.value)), note: `${x.value}${v.unit}` })), seconds: b.seconds };
    if (v.kind === "checklist") return { kind: "bars", title: `How careful is it: ${v.score}/100`, bars: v.items.map((x) => ({ label: x.label, value: x.met ? 100 : 2, note: x.met ? `+${x.points}` : "missing" })), seconds: b.seconds };
    if (v.kind === "flow") return { kind: "graph", center: "How it works", nodes: v.steps.map((s, i) => ({ name: s, label: `step ${i + 1}` })), seconds: b.seconds };
    return { kind: "say", kicker: { claims: "What it claims", quote: "The paper reports", curve: "Our toy check", questions: "Still open", sources: "Read it yourself" }[v.kind] || "", text: b.narration, small: b.narration.length > 220, seconds: b.seconds };
  }) };
}

// Build everything into dir. Rendering is skipped (with the command to run) when Manim or ffmpeg isn't installed.
function build(p, outDir, { render = true, quality = process.env.RESPONSE_QUALITY || "m", log = () => {} } = {}) {
  const dir = path.resolve(outDir); fs.mkdirSync(path.join(dir, "audio"), { recursive: true });
  const v = voice(), notes = [`Voice: ${v.label}.`], wavs = [];
  // 1) Narration first, so each beat lasts as long as its voice (plus a breath).
  for (const [i, b] of p.beats.entries()) {
    const f = speak(b.narration, path.join(dir, "audio", `${String(i + 1).padStart(2, "0")}-${b.id}.wav`), v);
    if (f) { const d = duration(f); if (d) b.seconds = Math.max(b.seconds, Math.ceil((d + 0.8) * 10) / 10); wavs.push({ file: f, seconds: b.seconds }); }
  }
  const sc = scene(p);
  fs.writeFileSync(path.join(dir, sc.file), sc.source);
  fs.writeFileSync(path.join(dir, "captions.srt"), captions(p.beats));
  fs.writeFileSync(path.join(dir, "narration.txt"), p.beats.map((b) => `[${b.id}, ${b.seconds}s] ${b.narration}`).join("\n\n") + "\n");
  fs.writeFileSync(path.join(dir, "storyboard.json"), JSON.stringify(playerStoryboard(p), null, 2));
  const files = ["scene.py", "captions.srt", "narration.txt", "storyboard.json", ...wavs.map((w) => path.relative(dir, w.file))];
  const total = p.beats.reduce((n, b) => n + b.seconds, 0);
  if (!render) { notes.push(`Not rendered (--no-render). Render: manim -q${quality} scene.py ${sc.className}`); return { files, notes, seconds: total, voice: v.id }; }
  if (!has("manim")) { notes.push(`Manim isn't installed (pip install manim). Render later: cd ${dir} && manim -q${quality} scene.py ${sc.className}`); return { files, notes, seconds: total, voice: v.id }; }
  log(`rendering ${total.toFixed(0)} s with Manim (-q${quality})…`);
  try { execFileSync("manim", [`-q${quality}`, "--disable_caching", "--media_dir", path.join(dir, "media"), "-o", "picture", path.join(dir, sc.file), sc.className], { cwd: dir, stdio: ["ignore", "ignore", "pipe"], timeout: 3600000 }); }
  catch (e) { throw new Error(`Manim couldn't render the scene: ${String(e.stderr || e.message).trim().split("\n").filter(Boolean).slice(-2).join(" ")}`); }
  const pic = findFile(path.join(dir, "media"), "picture.mp4"); if (!pic) throw new Error("Manim finished but no video was written.");
  if (!has("ffmpeg", ["-version"])) { fs.copyFileSync(pic, path.join(dir, "video.mp4")); notes.push("ffmpeg isn't installed: video.mp4 has no voice or subtitle track."); return { files: [...files, "video.mp4"], notes, seconds: total, voice: v.id }; }
  // 2) One narration track: each beat's wav padded to the beat's length, in order.
  const args = ["-y", "-loglevel", "error", "-i", pic];
  if (wavs.length) {
    const list = path.join(dir, "audio", "list.txt"), padded = [];
    wavs.forEach((w, i) => { const out = path.join(dir, "audio", `pad-${i}.wav`); execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-i", w.file, "-af", `apad=whole_dur=${w.seconds}`, "-ar", "22050", "-ac", "1", out]); padded.push(out); });
    fs.writeFileSync(list, padded.map((f) => `file '${f.replace(/'/g, "'\\''")}'`).join("\n"));
    execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", list, "-c:a", "pcm_s16le", path.join(dir, "narration.wav")]);
    args.push("-i", path.join(dir, "narration.wav"));
  }
  args.push("-i", path.join(dir, "captions.srt"), "-map", "0:v", ...(wavs.length ? ["-map", "1:a", "-c:a", "aac", "-b:a", "96k"] : []), "-map", `${wavs.length ? 2 : 1}:s`, "-c:v", "copy", "-c:s", "mov_text", "-metadata:s:s:0", "language=eng", "-movflags", "+faststart", path.join(dir, "video.mp4"));
  execFileSync("ffmpeg", args, { timeout: 600000 });
  notes.push(`Rendered video.mp4 (${duration(path.join(dir, "video.mp4")).toFixed(1)} s) with ${wavs.length ? "narration and " : ""}a subtitle track.`);
  return { files: [...files, ...(wavs.length ? ["narration.wav"] : []), "video.mp4"], notes, seconds: total, voice: v.id };
}
function findFile(dir, name) { if (!fs.existsSync(dir)) return null; for (const e of fs.readdirSync(dir, { withFileTypes: true })) { const p = path.join(dir, e.name); if (e.isDirectory()) { const f = findFile(p, name); if (f) return f; } else if (e.name === name) return p; } return null; }

module.exports = { scene, captions, playerStoryboard, build, voice, PALETTE };
